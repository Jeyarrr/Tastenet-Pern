CREATE TABLE IF NOT EXISTS suppliers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_code varchar(50) NOT NULL UNIQUE,
    supplier_name varchar(100) NOT NULL,
    contact_person varchar(100),
    email varchar(100),
    phone varchar(20),
    address varchar(255),
    tax_id varchar(50),
    is_active boolean DEFAULT true,
    created_at timestamptz DEFAULT now()
);

ALTER TABLE inventory ADD COLUMN IF NOT EXISTS supplier_id bigint REFERENCES suppliers(id) ON DELETE SET NULL;
ALTER TABLE inventory ADD COLUMN IF NOT EXISTS maximum_stock numeric(12,2);
ALTER TABLE inventory ADD COLUMN IF NOT EXISTS is_perishable boolean DEFAULT false;
ALTER TABLE inventory ADD COLUMN IF NOT EXISTS expiry_date date;
ALTER TABLE inventory ADD COLUMN IF NOT EXISTS last_stock_take date;
ALTER TABLE inventory_categories ADD COLUMN IF NOT EXISTS description varchar(255);
ALTER TABLE inventory_categories ADD COLUMN IF NOT EXISTS created_at timestamptz DEFAULT now();
ALTER TABLE inventory_transactions ADD COLUMN IF NOT EXISTS reference_number varchar(100);
ALTER TABLE delivery_fees ADD COLUMN IF NOT EXISTS created_at timestamptz DEFAULT now();
ALTER TABLE delivery_fees ADD COLUMN IF NOT EXISTS updated_at timestamptz DEFAULT now();
ALTER TABLE proofs ADD COLUMN IF NOT EXISTS proof_of_payment text;
ALTER TABLE proofs ALTER COLUMN proof_of_delivery DROP NOT NULL;
ALTER TABLE quotas ADD COLUMN IF NOT EXISTS created_at timestamptz DEFAULT now();
ALTER TABLE quotas ADD COLUMN IF NOT EXISTS updated_at timestamptz DEFAULT now();
ALTER TABLE menu ALTER COLUMN food_type DROP NOT NULL;
ALTER TABLE menu ALTER COLUMN ratings DROP NOT NULL;
ALTER TABLE ticket_items ALTER COLUMN quantity TYPE numeric(10,2);

CREATE TABLE IF NOT EXISTS admin_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(200) NOT NULL UNIQUE,
    username varchar(100) NOT NULL UNIQUE,
    password_hash text NOT NULL,
    full_name varchar(200),
    role varchar(50),
    is_active boolean DEFAULT true,
    is_two_factor_enabled boolean DEFAULT false,
    two_factor_secret_key text,
    last_login_date timestamptz,
    last_login_ip varchar(50),
    created_at timestamptz DEFAULT now(),
    modified_at timestamptz DEFAULT now(),
    created_by varchar(100)
);

CREATE TABLE IF NOT EXISTS application_settings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_key varchar(100) NOT NULL UNIQUE,
    setting_value text,
    setting_data_type varchar(20),
    setting_category varchar(50),
    is_encrypted boolean DEFAULT false,
    created_at timestamptz DEFAULT now(),
    modified_at timestamptz DEFAULT now(),
    modified_by varchar(100)
);

CREATE TABLE IF NOT EXISTS audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_type varchar(50),
    table_name varchar(100),
    record_id varchar(100),
    old_value text,
    new_value text,
    performed_by varchar(100),
    performed_date timestamptz,
    ip_address varchar(50)
);

CREATE TABLE IF NOT EXISTS order_status_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id varchar(50),
    old_status varchar(20),
    new_status varchar(20),
    changed_by bigint REFERENCES users(id) ON DELETE SET NULL,
    changed_date timestamptz
);

CREATE TABLE IF NOT EXISTS purchase_orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_number varchar(50) NOT NULL UNIQUE,
    supplier_id bigint NOT NULL REFERENCES suppliers(id) ON DELETE RESTRICT,
    order_date timestamptz DEFAULT now(),
    expected_delivery date,
    actual_delivery date,
    status varchar(20),
    total_amount numeric(12,2),
    notes varchar(500),
    created_by bigint REFERENCES users(id) ON DELETE SET NULL,
    approved_by bigint REFERENCES users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS purchase_order_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id bigint NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
    inventory_id bigint NOT NULL REFERENCES inventory(id) ON DELETE RESTRICT,
    quantity numeric(12,2) NOT NULL,
    unit_cost numeric(12,2) NOT NULL,
    total_cost numeric(12,2) NOT NULL,
    quantity_received numeric(12,2)
);

CREATE TABLE IF NOT EXISTS transaction_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id bigint,
    old_value text,
    new_value text,
    change_type varchar(20),
    changed_by bigint REFERENCES users(id) ON DELETE SET NULL,
    change_date timestamptz
);
-- The BACPAC contains historical transaction IDs absent from InventoryTransactions.
ALTER TABLE transaction_audit DROP CONSTRAINT IF EXISTS transaction_audit_transaction_id_fkey;

COMMIT;
